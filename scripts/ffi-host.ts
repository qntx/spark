/// <reference types="node" />
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// Builds spark-ffi as a static library, renders the ffi vectors into a C
// include (crates/spark-ffi/tests/host/main.c consumes vectors.inc), compiles
// the host test with the system C compiler against include/qntx_spark.h, and
// runs it. Exits non-zero when any step fails.

type JsonObject = Record<string, unknown>;

function isRecord(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null;
}

function asRecord(value: unknown): JsonObject {
  return isRecord(value) ? value : {};
}

function asString(value: unknown): string {
  return typeof value === "string" ? value : "";
}

function cases(name: string): JsonObject[] {
  const doc = asRecord(JSON.parse(readFileSync(`vectors/${name}`, "utf8")));
  return (Array.isArray(doc["cases"]) ? doc["cases"] : []).map(asRecord);
}

function cArray(name: string, values: string[]): string {
  const items = values.map((v) => `  "${v}"`).join(",\n");
  return `static const char *${name}[] = {\n${items}\n};\n`;
}

function run(cmd: string, args: string[]): void {
  console.log(`$ ${cmd} ${args.join(" ")}`);
  execFileSync(cmd, args, { stdio: "inherit" });
}

// The 257-job request is large; keep the include under the C89 minimum
// translation limit by emitting every string anyway (modern compilers allow
// much larger literals — the generated file is a test fixture, not a source
// of truth).
const sign = cases("ffi-sign.json");
const aggregate = cases("ffi-aggregate.json");
const errors = cases("ffi-errors.json");
const ecies = cases("ecies.json")[0] ?? {};

const errorRows = errors.map((c) => {
  const fn = asString(c["function"]);
  const arg = (key: string) => asString(c[key]);
  const num = (key: string) => (typeof c[key] === "number" ? c[key] : 0);
  let a = "";
  let b = "";
  let d = "";
  let n1 = 0;
  let n2 = 0;
  if (fn === "frost_commit") {
    a = arg("hedge");
    b = arg("random");
  } else if (fn === "frost_sign" || fn === "frost_aggregate") {
    a = arg("request");
  } else if (fn === "ecies_encrypt") {
    a = arg("public_key");
    b = arg("plaintext");
    d = arg("random");
  } else if (fn === "ecies_decrypt") {
    a = arg("secret_key");
    b = arg("ciphertext");
  } else if (fn === "split_secret_with_proofs") {
    a = arg("secret");
    d = arg("random");
    n1 = num("threshold");
    n2 = num("shares");
  }
  return `  { "${fn}", "${a}", "${b}", "${d}", ${String(n1)}, ${String(n2)}, ${String(num("code"))} }`;
});

const include = `/* Generated by scripts/ffi-host.ts — do not edit. */
#define ECIES_PUBLIC_KEY "${asString(ecies["public_key"])}"
#define ECIES_SECRET_KEY "${asString(ecies["secret_key"])}"
#define ECIES_PLAINTEXT "${asString(ecies["plaintext"])}"
#define ECIES_CIPHERTEXT "${asString(ecies["ciphertext"])}"
#define ECIES_RANDOM "${asString(ecies["random"])}"

typedef struct {
  const char *function;
  const char *a;
  const char *b;
  const char *d;
  long n1;
  long n2;
  int code;
} ErrCase;

${cArray(
  "FFI_SIGN_REQUESTS",
  sign.map((c) => asString(c["request"])),
)}${cArray(
  "FFI_SIGN_RESPONSES",
  sign.map((c) => asString(c["response"])),
)}${cArray(
  "FFI_AGGREGATE_REQUESTS",
  aggregate.map((c) => asString(c["request"])),
)}${cArray(
  "FFI_AGGREGATE_RESPONSES",
  aggregate.map((c) => asString(c["response"])),
)}
static const ErrCase FFI_ERRORS[] = {
${errorRows.join(",\n")}
};

#define FFI_SIGN_COUNT (sizeof(FFI_SIGN_REQUESTS) / sizeof(*FFI_SIGN_REQUESTS))
#define FFI_AGGREGATE_COUNT \\
  (sizeof(FFI_AGGREGATE_REQUESTS) / sizeof(*FFI_AGGREGATE_REQUESTS))
#define FFI_ERROR_COUNT (sizeof(FFI_ERRORS) / sizeof(*FFI_ERRORS))
`;

const work = mkdtempSync(join(tmpdir(), "spark-ffi-host-"));
writeFileSync(join(work, "vectors.inc"), include);

run("cargo", ["build", "-p", "spark-ffi", "--release"]);

const staticlib = join("target", "release", "libspark_ffi.a");
const binary = join(work, "ffi-host");
const platformLibs = process.platform === "darwin" ? [] : ["-lpthread", "-ldl", "-lm"];
run("cc", [
  "-std=c11",
  "-O2",
  "-Wall",
  "-Wextra",
  "-Werror",
  "-I",
  "crates/spark-ffi/include",
  "-I",
  work,
  "crates/spark-ffi/tests/host/main.c",
  staticlib,
  ...platformLibs,
  "-o",
  binary,
]);
run(binary, []);

// C++ linkage guard: the ABI header must declare extern "C" (cbindgen
// cpp_compat) — without it a C++ TU references mangled symbols and this
// link fails even though the C build above passed.
const cppSource = `#include "qntx_spark.h"
int main() { return static_cast<int>(qs_abi_version()) == 1 ? 0 : 1; }
`;
writeFileSync(join(work, "linkage.cpp"), cppSource);
run("c++", [
  "-std=c++17",
  "-O0",
  "-Wall",
  "-Werror",
  "-I",
  "crates/spark-ffi/include",
  join(work, "linkage.cpp"),
  staticlib,
  ...platformLibs,
  "-o",
  join(work, "ffi-linkage"),
]);
run(join(work, "ffi-linkage"), []);
console.log("ffi-linkage: c++ consumer linked and ran");
