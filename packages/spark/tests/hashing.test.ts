function b64ToBytes(value: string): Uint8Array {
  return Uint8Array.from(atob(value), (ch) => ch.codePointAt(0) ?? 0);
}

function sparkNetworkOf(value: string): SparkNetwork {
  const network = value.toLowerCase();
  if (network !== "mainnet" && network !== "regtest") {
    throw new Error(`unexpected network ${value}`);
  }
  return network;
}

