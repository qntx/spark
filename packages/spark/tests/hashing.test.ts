const VECTORS = loadJsonFile(resolve(vectorsDir, "hashing.json")) as HashingVectors;

function optHex(hex: string | null | undefined): Uint8Array | undefined {
  return hex === undefined || hex === null ? undefined : hexToBytes(hex);
}

function replayHasherOps(tag: ReadonlyArray<string>, values: HasherOp[]): Hasher {
  const h = newHasher(tag);
  for (const op of values) {
    if ("bytes" in op) {
      h.addBytes(hexToBytes(op.bytes));
    } else if ("string" in op) {
      h.addString(op.string);
    } else if ("uint8" in op) {
      h.addUint8(op.uint8);
    } else if ("uint16" in op) {
      h.addUint16(op.uint16);
    } else if ("uint32" in op) {
      h.addUint32(op.uint32);
    } else if ("uint64" in op) {
      h.addUint64(BigInt(op.uint64));
    } else {
      h.addMapStringToBytes(
        Object.fromEntries(Object.entries(op.mapStringToBytes).map(([k, v]) => [k, hexToBytes(v)])),
      );
    }
  }
  return h;
}

