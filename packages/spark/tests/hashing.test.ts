test("per-leaf send signature digest is sha256(utf8(leafId) ‖ utf8(transferId) ‖ secretCipher)", () => {
  // Layout reference: spark/testing/wallet/transfer.go + SDK services/transfer.ts.
  const leafId = "11111111-2222-4333-8444-555555555555";
  const digest = sendLeafSigningDigest(leafId, GO_TRANSFER_ID, GO_SSP_SIG);
  const expected = sha256(
    concatBytes(utf8ToBytes(leafId), utf8ToBytes(GO_TRANSFER_ID), GO_SSP_SIG),
  );
  expect(digest).toStrictEqual(expected);
});

